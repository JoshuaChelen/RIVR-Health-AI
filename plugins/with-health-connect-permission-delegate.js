// Config plugin: register react-native-health-connect's permission delegate.
//
// The library's requestPermission() launches an ActivityResultLauncher stored in
// a `lateinit var requestPermission` that MUST be initialized by calling
// HealthConnectPermissionDelegate.setPermissionDelegate(this) in MainActivity.onCreate.
// Without it, tapping "Connect" crashes:
//   kotlin.UninitializedPropertyAccessException: lateinit property requestPermission
//   has not been initialized  (HealthConnectPermissionDelegate.launchPermissionsDialog)
//
// The library's own app.plugin.js only patches AndroidManifest (the rationale
// intent-filter), NOT MainActivity. This project uses Continuous Native
// Generation (android/ is gitignored and regenerated by prebuild/EAS), so the
// MainActivity edit must be applied here as a config plugin rather than by hand.
const { withMainActivity } = require("@expo/config-plugins");

const IMPORT = "import dev.matinzd.healthconnect.permissions.HealthConnectPermissionDelegate";
const CALL = "HealthConnectPermissionDelegate.setPermissionDelegate(this)";

module.exports = function withHealthConnectPermissionDelegate(config) {
  return withMainActivity(config, (cfg) => {
    if (cfg.modResults.language !== "kt") {
      throw new Error(
        "with-health-connect-permission-delegate expects a Kotlin MainActivity",
      );
    }
    let src = cfg.modResults.contents;

    // 1. import (idempotent), placed right after the package declaration.
    if (!src.includes(IMPORT)) {
      src = src.replace(/^(package .*)$/m, `$1\n\n${IMPORT}`);
    }

    // 2. register the delegate immediately after super.onCreate(...) (idempotent).
    if (!src.includes(CALL)) {
      src = src.replace(/(super\.onCreate\([^)]*\))/, `$1\n    ${CALL}`);
    }

    cfg.modResults.contents = src;
    return cfg;
  });
};
